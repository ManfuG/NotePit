package io.notepit.app

import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.channels.Channel
import kotlinx.coroutines.delay
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock

/** Main-confined requests; a cancelled worker returns ownership before its replacement runs. */
internal class IndexRefreshQueue {
    private val wakeups = Channel<Unit>(Channel.CONFLATED)
    private val consumer = Mutex()
    private var required = false
    private var forced = false

    fun request(force: Boolean = false, providerHint: Boolean = false) {
        required = required || !providerHint || force
        forced = forced || force
        wakeups.trySend(Unit)
    }

    suspend fun run(refresh: suspend (Boolean) -> Boolean) = consumer.withLock {
        var validation = false
        for (ignored in wakeups) {
            var force = false
            try {
                delay(650)
                while (wakeups.tryReceive().isSuccess) { }
                force = forced
                val normal = required || !validation
                required = false
                forced = false
                val changed = refresh(force)
                // Every normal pass validates intervening hints, even if it changed nothing.
                // Only a stable validation can acknowledge feedback generated by its own reads.
                if (!normal && !changed && !required && !forced) {
                    while (wakeups.tryReceive().isSuccess) { }
                    validation = false
                } else {
                    val pending = wakeups.tryReceive().isSuccess
                    validation = pending && !required
                    if (pending) wakeups.trySend(Unit)
                }
            } catch (cancelled: CancellationException) {
                request(force = force)
                throw cancelled
            } catch (failure: Exception) {
                request(force = force)
                throw failure
            }
        }
    }
}
